"""Read-only sitemap-vs-published integrity invariant (Nomadomics QA F-01, 2026-10-08).

The production sitemap is generated by the Next.js frontend from the live
Strapi ``status=published`` set and served through Vercel's ISR cache. On
2026-10-08 it advertised ``cost-of-living-cape-town-nomads`` while live Strapi
returned that article as ``in_review`` and the production URL returned 404 —
the stale-cache shape (render from before the withdrawal, ``age: 41655``,
``x-vercel-cache: HIT``). Reproduction at implementation time: sitemap still
carried the slug (59 locs) while the live published set (46) did not.

This module is the regression invariant: it compares the LIVE sitemap's
article-URL set against the LIVE published slug set, names both sets in its
output, and exercises every sitemap-emitted article URL for HTTP 200.

Safety rules (read-only, fail-closed):
  * NEVER writes Strapi, never changes publication status, never deletes or
    replaces content.
  * Unavailable dependency != failed invariant. A sitemap that is unreachable
    or non-200, a CMS that errors/401s, or a CMS response with ZERO rows is a
    ``DependencyError`` (exit 2) — never a pass, never a fail. In particular
    an unauthenticated/empty CMS response is NOT interpreted as "zero
    published articles" (criterion 3; no fail-open with an empty set).
  * The invariant FAILS (exit 1) exactly when the sitemap advertises a slug
    the live published set does not (``sitemap_only``) or a sitemap-emitted
    article URL does not return HTTP 200.
  * ``published_only`` drift is reported but is not a failure: a freshly
    published article legitimately lags the sitemap until the next ISR
    revalidate (``revalidate = 3600`` in ``frontend/src/app/sitemap.ts``).

Usage:
    env -u PYTHONPATH .venv/bin/python -m engine.cli sitemap-check
    env -u PYTHONPATH .venv/bin/python -m engine.sitemap_integrity [--url <sitemap-url>]
Exit: 0 pass, 1 invariant failed, 2 dependency unavailable.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import urljoin, urlsplit

_ENGINE_DIR = Path(__file__).resolve().parent
if str(_ENGINE_DIR) not in sys.path:
    sys.path.insert(0, str(_ENGINE_DIR))

import httpx

from config import Config, load_config
from strapi import StrapiClient

DEFAULT_SITEMAP_URL = "https://www.nomadomics.blog/sitemap.xml"
DEFAULT_SITE_URL = "https://www.nomadomics.blog"
PUBLISHED_SOURCE = "Strapi /api/articles?filters[status][$eq]=published"

# Single-segment paths the sitemap legitimately emits alongside articles
# (homepage, about, privacy, category index, author index).
_NON_ARTICLE_SEGMENTS = {"", "about", "privacy", "category", "author"}

_LOC_RE = re.compile(r"<loc>\s*(.*?)\s*</loc>", re.S)
_ROOT_RE = re.compile(r"<([a-zA-Z]+)[^>]*>")


class DependencyError(Exception):
    """An upstream dependency (sitemap or CMS) is unavailable — not an invariant failure."""


@dataclass
class IntegrityReport:
    """Named-set comparison + per-URL exercise result.

    ``failed`` is False when ``dependency_error`` is set — an unavailable
    dependency is never a verdict. ``verdict`` is one of "PASS" / "FAIL" /
    "unavailable".
    """

    sitemap_url: str
    published_source: str
    sitemap_locs_total: int = 0
    sitemap_article_slugs: set = field(default_factory=set)
    published_article_slugs: set = field(default_factory=set)
    sitemap_only: set = field(default_factory=set)
    published_only: set = field(default_factory=set)
    non200: list = field(default_factory=list)  # [(url, status)]
    dependency_error: str | None = None

    @property
    def failed(self) -> bool:
        return self.dependency_error is None and bool(self.sitemap_only or self.non200)

    @property
    def verdict(self) -> str:
        if self.dependency_error:
            return "unavailable"
        return "FAIL" if self.failed else "PASS"


# ---- URL normalisation / sitemap parsing (pure, no I/O) ----------------------


def _decode_entities(text: str) -> str:
    """Decode the XML entities a <loc> may carry (&amp; &lt; &gt; &quot; &#39;)."""
    return (
        text.replace("&amp;", "&")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", '"')
        .replace("&#39;", "'")
    )


def _host_key(host: str | None) -> str:
    """Comparable host key — strips scheme, case and the leading ``www.`` so
    ``www.nomadomics.blog`` and ``nomadomics.blog`` compare equal (the frontend
    emits the apex from ``NEXT_PUBLIC_SITE_URL`` while the sitemap is served at
    www)."""
    h = (host or "").lower().strip().rstrip(".")
    return h[4:] if h.startswith("www.") else h


def _absolute(loc: str, site_url: str) -> str:
    """Resolve a <loc> to an absolute URL. Accepts absolute, site-relative
    (``/slug``) and bare-relative (``about``) values — criterion 2."""
    loc = loc.strip()
    if loc.startswith("/"):
        return site_url.rstrip("/") + loc
    if re.match(r"^https?://", loc, re.I):
        return loc
    return urljoin(site_url.rstrip("/") + "/", loc)


def _is_article(abs_url: str, site_url: str) -> bool:
    """True when ``abs_url`` is a same-origin, single-segment path that is not
    one of the known non-article pages."""
    parts = urlsplit(abs_url)
    site = urlsplit(site_url)
    if _host_key(parts.hostname) != _host_key(site.hostname):
        return False
    segs = [s for s in parts.path.split("/") if s]
    if len(segs) != 1:
        return False
    return segs[0] not in _NON_ARTICLE_SEGMENTS


def _slug_for(abs_url: str, site_url: str) -> str | None:
    """Article slug for an absolute URL, or None for non-article URLs."""
    if not _is_article(abs_url, site_url):
        return None
    return urlsplit(abs_url).path.strip("/").split("/")[0]


def parse_sitemap(xml: str, *, site_url: str = DEFAULT_SITE_URL) -> tuple[list[str], list[str]]:
    """``(article_urls, non_article_urls)`` from sitemap XML, in document order.

    Accepts a ``urlset`` (the production shape). A ``sitemapindex`` root is
    refused — its <loc>s are child sitemaps that must be fetched individually,
    so an index alone cannot be compared (``DependencyError``).
    """
    m = _ROOT_RE.search(xml.lstrip())
    root_name = (m.group(1) if m else "").lower()
    if root_name == "sitemapindex":
        raise DependencyError(
            "sitemap is a sitemap index, not a urlset — the child sitemaps must "
            "be fetched and compared individually"
        )
    article: list[str] = []
    non_article: list[str] = []
    for raw in _LOC_RE.findall(xml):
        url = _decode_entities(raw).strip()
        if not url:
            continue
        abs_url = _absolute(url, site_url)
        if _is_article(abs_url, site_url):
            article.append(abs_url)
        else:
            non_article.append(abs_url)
    return article, non_article


def analyze(
    xml: str,
    published_slugs: set,
    *,
    site_url: str = DEFAULT_SITE_URL,
    sitemap_url: str = DEFAULT_SITEMAP_URL,
    url_status=None,
) -> IntegrityReport:
    """Pure invariant: compare the sitemap's article slugs against the published
    set and exercise every emitted article URL.

    ``url_status(url) -> int`` is the per-URL HTTP check; when None (offline
    use) URLs are not exercised and ``non200`` stays empty. An empty
    ``published_slugs`` raises ``DependencyError`` — an unauthenticated/empty
    CMS response must never read as "zero published articles" (criterion 3).
    """
    if not published_slugs:
        raise DependencyError(
            "refusing to interpret an EMPTY published-article set as zero "
            "published articles — an unauthenticated/empty CMS response is a "
            "dependency error, not a pass"
        )
    article_urls, _ = parse_sitemap(xml, site_url=site_url)
    sitemap_slugs = {_slug_for(u, site_url) for u in article_urls}
    sitemap_slugs.discard(None)
    published = {str(s or "").strip() for s in published_slugs}
    published.discard("")

    non200: list = []
    if url_status is not None:
        for url in article_urls:
            try:
                status = int(url_status(url) or 0)
            except Exception:  # noqa: BLE001 — a failed probe is a failed check
                status = 0
            if status != 200:
                non200.append((url, status))

    return IntegrityReport(
        sitemap_url=sitemap_url,
        published_source=PUBLISHED_SOURCE,
        sitemap_locs_total=len(_LOC_RE.findall(xml)),
        sitemap_article_slugs=sitemap_slugs,
        published_article_slugs=published,
        sitemap_only=sitemap_slugs - published,
        published_only=published - sitemap_slugs,
        non200=non200,
    )


# ---- Network layer (the only place that opens connections) -------------------


def fetch_sitemap_xml(url: str, http) -> str:
    """GET the sitemap; raise ``DependencyError`` on any non-200 or empty body.
    ``http`` is an ``httpx.Client`` (or a test double with ``.get``)."""
    try:
        resp = http.get(url, follow_redirects=True, timeout=30)
    except httpx.HTTPError as e:
        raise DependencyError(f"sitemap fetch failed ({type(e).__name__}): {url}") from e
    if resp.status_code != 200:
        raise DependencyError(f"sitemap returned HTTP {resp.status_code}: {url}")
    body = resp.text or ""
    if not body.strip():
        raise DependencyError(f"sitemap returned an EMPTY body: {url}")
    return body


def fetch_published_slugs(client) -> set:
    """Live Strapi ``status=published`` slugs.

    Fail-closed: any transport/API error, and ANY response with zero slugs, is
    a ``DependencyError`` — an unauthenticated/empty CMS response is never
    treated as a legitimately empty published set (criterion 3).
    """
    try:
        data = client._request(
            "GET",
            "/api/articles",
            params={"filters[status][$eq]": "published", "pagination[pageSize]": 500},
        )
    except Exception as e:  # noqa: BLE001 — StrapiError or transport
        raise DependencyError(f"Strapi published-articles fetch failed: {e}") from e
    rows = data.get("data") or []
    slugs = {str(r.get("slug") or "").strip() for r in rows}
    slugs.discard("")
    if not slugs:
        raise DependencyError(
            "Strapi returned ZERO published article slugs — refusing to interpret "
            "an unauthenticated/empty CMS response as zero published articles"
        )
    return slugs


def _url_status_from(http):
    """Per-URL HTTP check used by the CLI. Network errors read as status 0
    (a URL we could not verify is conservatively not a 200)."""

    def status(url: str) -> int:
        try:
            resp = http.get(url, follow_redirects=True, timeout=15)
            return resp.status_code
        except httpx.HTTPError:
            return 0

    return status


def run_integrity(
    *,
    config: Config | None = None,
    client=None,
    http_client=None,
    sitemap_url: str = DEFAULT_SITEMAP_URL,
) -> IntegrityReport:
    """Fetch both live sets and run the invariant. A ``DependencyError`` at any
    step yields an ``unavailable`` report (never pass, never fail).

    ``client`` is a Strapi client (created from ``config`` when omitted) and
    ``http_client`` an ``httpx.Client`` for the public sitemap/URL endpoints
    (owned and closed here when not injected) — both injectable for tests.
    """
    cfg = config or load_config()
    close_strapi = client is None
    close_http = http_client is None
    strapi = client if client is not None else StrapiClient(cfg)
    http = http_client if http_client is not None else httpx.Client(timeout=30)
    try:
        xml = fetch_sitemap_xml(sitemap_url, http)
        published = fetch_published_slugs(strapi)
        return analyze(
            xml, published, sitemap_url=sitemap_url, url_status=_url_status_from(http)
        )
    except DependencyError as e:
        return IntegrityReport(
            sitemap_url=sitemap_url, published_source=PUBLISHED_SOURCE,
            dependency_error=str(e),
        )
    finally:
        if close_http:
            http.close()
        if close_strapi:
            strapi.close()


# ---- Output / exit codes ------------------------------------------------------


def format_report(r: IntegrityReport) -> list[str]:
    """Named-set report lines (criterion 2: the compared sets are named)."""
    if r.dependency_error:
        return [
            f"sitemap-integrity: UNAVAILABLE — {r.dependency_error}",
            "sitemap-integrity: (an unavailable dependency is not a pass and not a failed invariant)",
        ]
    lines = [
        f"sitemap-integrity: sitemap={r.sitemap_url}",
        f"sitemap-integrity: published_source={r.published_source}",
        (
            f"sitemap-integrity: sets: sitemap_article_slugs={len(r.sitemap_article_slugs)} "
            f"published_article_slugs={len(r.published_article_slugs)} "
            f"sitemap_only={len(r.sitemap_only)} published_only={len(r.published_only)}"
        ),
    ]
    for slug in sorted(r.sitemap_only):
        lines.append(f"sitemap-integrity:   sitemap_only: /{slug}")
    for slug in sorted(r.published_only):
        lines.append(
            f"sitemap-integrity:   published_only: /{slug} "
            "(transient if just published — the sitemap revalidates hourly)"
        )
    for url, status in r.non200:
        lines.append(f"sitemap-integrity:   non200: {url} -> HTTP {status}")
    if r.failed:
        lines.append(
            f"sitemap-integrity: FAIL — stale sitemap: {len(r.sitemap_only)} sitemap-only "
            f"slug(s), {len(r.non200)} emitted article URL(s) not HTTP 200"
        )
    else:
        lines.append(
            "sitemap-integrity: PASS — every sitemap article URL is in the live "
            "published set and returns HTTP 200"
        )
    return lines


def run_sitemap_check(
    *,
    config: Config | None = None,
    client=None,
    http_client=None,
    sitemap_url: str = DEFAULT_SITEMAP_URL,
) -> int:
    """CLI entry: print the named-set report and return the exit code
    (0 pass, 1 invariant failed, 2 dependency unavailable)."""
    report = run_integrity(
        config=config, client=client, http_client=http_client, sitemap_url=sitemap_url
    )
    for line in format_report(report):
        print(line)
    if report.dependency_error:
        return 2
    return 1 if report.failed else 0


def main(argv: list | None = None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    sitemap_url = DEFAULT_SITEMAP_URL
    if "--url" in argv:
        i = argv.index("--url")
        if i + 1 >= len(argv) or argv[i + 1].startswith("-"):
            print(
                "usage: python -m engine.sitemap_integrity [--url <sitemap-url>]",
                file=sys.stderr,
            )
            return 2
        sitemap_url = argv[i + 1]
    try:
        cfg = load_config()
    except RuntimeError as e:
        print(f"sitemap-integrity: {e}", file=sys.stderr)
        return 2
    client = StrapiClient(cfg)
    try:
        return run_sitemap_check(config=cfg, client=client, sitemap_url=sitemap_url)
    finally:
        client.close()


if __name__ == "__main__":
    sys.exit(main())
